package com.privacyshield;

import com.google.zxing.BarcodeFormat;
import com.google.zxing.EncodeHintType;
import com.google.zxing.WriterException;
import com.google.zxing.client.j2se.MatrixToImageWriter;
import com.google.zxing.common.BitMatrix;
import com.google.zxing.qrcode.QRCodeWriter;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import javax.imageio.ImageIO;
import java.awt.Color;
import java.awt.Graphics2D;
import java.awt.Rectangle;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Collections;
import java.util.EnumMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Tests QR detection with synthetic QR codes generated by ZXing.
 *
 * The encoded text is made up and does not belong to a real person.
 */
class QrCodeServiceTest {
    private final QrCodeService service = new QrCodeService();

    @Test
    void scanFindsOneQrCode(@TempDir Path temp) throws Exception {
        String text = "Contact person@example.com";
        File photo = writeQrPhoto(temp, "one.png", 320, 320, 30, 30, text);

        List<QrCodeResult> results = service.scan(photo);

        assertEquals(1, results.size());
        assertEquals(text, results.get(0).getText());
        assertTrue(results.get(0).getBounds().contains(160, 160));
        assertTrue(results.get(0).getBounds().width <= 320);
        assertTrue(results.get(0).getBounds().height <= 320);
    }

    @Test
    void scanFindsTwoQrCodesInOnePhoto(@TempDir Path temp) throws Exception {
        BufferedImage first = qrCode("PAN ABCPD1234E", 240);
        BufferedImage second = qrCode("Phone +91 98765 43210", 240);
        BufferedImage photo = new BufferedImage(620, 320, BufferedImage.TYPE_INT_RGB);
        Graphics2D graphics = photo.createGraphics();
        graphics.setColor(Color.WHITE);
        graphics.fillRect(0, 0, photo.getWidth(), photo.getHeight());
        graphics.drawImage(first, 20, 40, null);
        graphics.drawImage(second, 350, 40, null);
        graphics.dispose();

        File file = temp.resolve("two.png").toFile();
        ImageIO.write(photo, "png", file);

        List<QrCodeResult> results = service.scan(file);

        assertEquals(2, results.size());
        Set<String> texts = new HashSet<String>();
        for (QrCodeResult result : results) {
            texts.add(result.getText());
        }
        assertEquals(new HashSet<String>(Arrays.asList(
                "PAN ABCPD1234E", "Phone +91 98765 43210")), texts);
    }

    @Test
    void plainPhotoHasNoQrCode(@TempDir Path temp) throws Exception {
        BufferedImage photo = new BufferedImage(200, 120, BufferedImage.TYPE_INT_RGB);
        Graphics2D graphics = photo.createGraphics();
        graphics.setColor(new Color(0x30, 0x80, 0xC0));
        graphics.fillRect(0, 0, photo.getWidth(), photo.getHeight());
        graphics.dispose();

        File file = temp.resolve("plain.png").toFile();
        ImageIO.write(photo, "png", file);

        assertTrue(service.scan(file).isEmpty());
    }

    @Test
    void redactionRemovesTheQrCode(@TempDir Path temp) throws Exception {
        File photo = writeQrPhoto(temp, "qr.png", 320, 320, 30, 30,
                "Aadhaar 2345 6789 0124");
        List<QrCodeResult> results = service.scan(photo);
        assertEquals(1, results.size());

        Rectangle bounds = results.get(0).getBounds();
        File clean = temp.resolve("clean.png").toFile();
        new PhotoService().redact(photo, clean, Collections.singletonList(bounds));

        assertTrue(service.scan(clean).isEmpty());

        BufferedImage image = ImageIO.read(clean);
        assertEquals(Color.BLACK.getRGB(),
                image.getRGB(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2));
    }

    @Test
    void missingFilesAndNullsAreRejected(@TempDir Path temp) {
        assertThrows(IOException.class,
                () -> service.scan(temp.resolve("missing.png").toFile()));
        assertThrows(IllegalArgumentException.class, () -> service.scan((File) null));
        assertThrows(IllegalArgumentException.class, () -> service.scan((BufferedImage) null));
    }

    private static File writeQrPhoto(Path temp, String name, int width, int height,
                                     int x, int y, String text) throws Exception {
        BufferedImage photo = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
        Graphics2D graphics = photo.createGraphics();
        graphics.setColor(Color.WHITE);
        graphics.fillRect(0, 0, width, height);
        graphics.drawImage(qrCode(text, 220), x, y, null);
        graphics.dispose();

        File file = temp.resolve(name).toFile();

        if (!ImageIO.write(photo, "png", file)) {
            throw new IOException("Could not write the test image.");
        }

        return file;
    }

    private static BufferedImage qrCode(String text, int size) throws WriterException {
        Map<EncodeHintType, Object> hints = new EnumMap<EncodeHintType, Object>(EncodeHintType.class);
        hints.put(EncodeHintType.MARGIN, 2);
        hints.put(EncodeHintType.CHARACTER_SET, "UTF-8");

        BitMatrix matrix = new QRCodeWriter().encode(
                text, BarcodeFormat.QR_CODE, size, size, hints);
        return MatrixToImageWriter.toBufferedImage(matrix);
    }
}
